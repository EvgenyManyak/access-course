-- =====================================================================================
-- aggregate-queries.sql — итоговые (агрегатные) запросы: GROUP BY, SUM/AVG/MIN/MAX,
-- COUNT, HAVING, ROUND. Курс «Microsoft Access 2007–2016 для аналитика», модуль 8.
--
-- НАЗНАЧЕНИЕ ФАЙЛА
--   Восемь запросов к мини-датасету ShopData. Эталонная выручка без отменённых заказов:
--   3 025,50 (delivered + shipped + processing; отменён только O-10006 на 89,90).
--
-- ПОДГОТОВКА (один раз, нужна для блоков 7 и 8)
--   Сохраните как qry_ВыручкаЗаказов следующий оператор — он считает выручку КАЖДОГО заказа
--   отдельной строкой и защищает от задвоения заказов при соединении с позициями:
--       SELECT od.OrderID, o.CustomerID, o.ManagerID,
--              SUM(od.Quantity * od.UnitPrice) AS ВыручкаЗаказа
--       FROM Orders AS o INNER JOIN OrderDetails AS od ON o.OrderID = od.OrderID
--       WHERE o.OrderStatus <> "canceled"
--       GROUP BY od.OrderID, o.CustomerID, o.ManagerID;
--   Ожидаемый результат qry_ВыручкаЗаказов: 11 строк (без O-10006), например
--   O-10001 = 369,70; O-10002 = 149,00; O-10003 = 776,50; O-10004 = 259,80; O-10005 = 239,60;
--   O-10007 = 283,50; O-10008 = 189,90; O-10009 = 298,00; O-10010 = 59,90; O-10011 = 269,70;
--   O-10012 = 129,90. Сумма столбца = 3 025,50.
--
-- КАК ИСПОЛЬЗОВАТЬ
--   Режим SQL конструктора запросов, вставлять ОДИН оператор за раз (строки «--» не копируются —
--   комментарии в Access не работают). Каждый оператор самодостаточен, кроме блоков 7–8,
--   которым нужен сохранённый qry_ВыручкаЗаказов из шапки.
-- =====================================================================================


-- ---------------------------------------------------------------------------------------------
-- 1. COUNT: сколько всего заказов и сколько из них доставлено
-- COUNT(*) считает ВСЕ строки; COUNT(поле) — только строки, где поле заполнено (пустые пропускает).
-- Ожидаемый результат: одна строка: [Всего заказов] = 12, [С датой доставки] = 9
--   (DeliveredDate пуст у O-10005, O-10006, O-10010).
-- ---------------------------------------------------------------------------------------------
SELECT COUNT(*) AS [Всего заказов], COUNT(DeliveredDate) AS [С датой доставки]
FROM Orders;


-- ---------------------------------------------------------------------------------------------
-- 2. SUM по категориям: выручка без отменённых заказов
-- Соединяем 4 таблицы, фильтруем статусы и группируем по английскому имени категории.
-- Ожидаемый результат: 5 строк по убыванию:
--   bed_bath_table 769,50; computers_accessories 746,50; furniture_decor 640,00;
--   health_beauty 631,50; auto 238,00. Контрольная сумма: 3 025,50.
-- СВЕРКА ЭТАЛОНА: в ТЗ фигурировало значение bed_bath_table = 891,20, но пересчёт по
--   мини-датасету даёт 769,50: P-1001 — 189,90 (O-10001) + 189,90 (O-10008) = 379,80;
--   P-1002 — 129,90 x 2 (O-10004) + 129,90 (O-10012) = 389,70; итого 769,50.
--   В этом файле используется выверенное значение 769,50.
-- ---------------------------------------------------------------------------------------------
SELECT cat.CategoryNameEn AS Категория, SUM(od.Quantity * od.UnitPrice) AS Выручка
FROM ((OrderDetails AS od INNER JOIN Products AS p ON od.ProductID = p.ProductID)
     INNER JOIN Categories AS cat ON p.CategoryID = cat.CategoryID)
     INNER JOIN Orders AS o ON od.OrderID = o.OrderID
WHERE o.OrderStatus IN ("delivered", "shipped", "processing")
GROUP BY cat.CategoryNameEn
ORDER BY SUM(od.Quantity * od.UnitPrice) DESC;


-- ---------------------------------------------------------------------------------------------
-- 3. AVG / MIN / MAX по цене позиции
-- Ожидаемый результат: одна строка: Средняя = 145,14; Минимальная = 45,50 (P-2002);
--   Максимальная = 640,00 (P-4001). Проверка: сумма 15 цен = 2 177,10, 2 177,10 / 15 = 145,14.
-- ---------------------------------------------------------------------------------------------
SELECT AVG(UnitPrice) AS Средняя, MIN(UnitPrice) AS Минимальная, MAX(UnitPrice) AS Максимальная
FROM OrderDetails;


-- ---------------------------------------------------------------------------------------------
-- 4. GROUP BY по статусам заказов
-- Ожидаемый результат: 4 строки: delivered = 9; canceled = 1; processing = 1; shipped = 1.
--   При равном COUNT сортировка идёт по алфавиту статусов (canceled, processing, shipped).
-- ---------------------------------------------------------------------------------------------
SELECT OrderStatus, COUNT(*) AS Заказов
FROM Orders
GROUP BY OrderStatus
ORDER BY COUNT(*) DESC, OrderStatus;


-- ---------------------------------------------------------------------------------------------
-- 5. HAVING: категории с более чем одной позицией и средней ценой выше 100
-- HAVING фильтрует УЖЕ сгруппированные данные (WHERE фильтрует строки до группировки).
-- Здесь агрегаты считаются по всем 15 позициям, без фильтра по статусу.
-- Ожидаемый результат: 2 строки:
--   bed_bath_table — 4 позиции, средняя цена 159,90 (189,90 + 129,90 + 189,90 + 129,90 = 639,60 / 4);
--   computers_accessories — 4 позиции, средняя цена 104,45 (149,00 + 59,90 + 149,00 + 59,90 = 417,80 / 4).
--   health_beauty отсечена: средняя цена 72,14 (89,90 + 45,50 + 89,90 + 45,50 + 89,90 = 360,70 / 5);
--   furniture_decor и auto отпали по условию COUNT(*) > 1 (по одной позиции).
-- ---------------------------------------------------------------------------------------------
SELECT cat.CategoryNameEn AS Категория, COUNT(*) AS Позиций, AVG(od.UnitPrice) AS СредняяЦена
FROM (OrderDetails AS od INNER JOIN Products AS p ON od.ProductID = p.ProductID)
     INNER JOIN Categories AS cat ON p.CategoryID = cat.CategoryID
GROUP BY cat.CategoryNameEn
HAVING COUNT(*) > 1 AND AVG(od.UnitPrice) > 100
ORDER BY AVG(od.UnitPrice) DESC;


-- ---------------------------------------------------------------------------------------------
-- 6. ROUND: округление агрегатов
-- ROUND(число; число знаков) округляет по правилам математики (для значений, оканчивающихся
-- ровно на 5, Access применяет банковское округление — к чётной цифре; здесь это не встречается).
-- Ожидаемый результат: одна строка: СредняяЦелая = 145; Средняя1Знак = 145,1
--   (точное среднее 145,14 = 2 177,10 / 15).
-- ---------------------------------------------------------------------------------------------
SELECT ROUND(AVG(UnitPrice), 0) AS СредняяЦелая, ROUND(AVG(UnitPrice), 1) AS Средняя1Знак
FROM OrderDetails;


-- ---------------------------------------------------------------------------------------------
-- 7. Средний чек по покупателям (нужен qry_ВыручкаЗаказов из шапки)
-- Запрос строится ПОВЕРХ сохранённого запроса: qry_ВыручкаЗаказов возвращает одну строку на
-- заказ, поэтому COUNT даёт именно число заказов, а не позиций (без этого соединение с
-- OrderDetails умножило бы строки и «средний чек» оказался бы средним по позициям).
-- Ожидаемый результат: 7 строк по убыванию выручки:
--   Carla Mendes    2 заказа  1 046,20  средний 523,10
--   Ana Ribeiro     3 заказа    759,40  средний 253,13  (759,40 / 3)
--   Bruno Carvalho  2 заказа    447,00  средний 223,50
--   Felipe Alves    1 заказ     283,50  средний 283,50
--   Diego Silva     1 заказ     239,60  средний 239,60
--   Gabriela Lima   1 заказ     189,90  средний 189,90
--   Henrique Souza  1 заказ      59,90  средний 59,90
--   Elena Costa отсутствует: её единственный заказ O-10006 отменён и отфильтрован в qry_ВыручкаЗаказов.
--   Контроль: сумма столбца Выручка = 3 025,50.
-- ---------------------------------------------------------------------------------------------
SELECT c.CustomerName, COUNT(z.OrderID) AS Заказов,
       SUM(z.ВыручкаЗаказа) AS Выручка,
       ROUND(SUM(z.ВыручкаЗаказа) / COUNT(z.OrderID), 2) AS [Средний чек]
FROM qry_ВыручкаЗаказов AS z INNER JOIN Customers AS c ON z.CustomerID = c.CustomerID
GROUP BY c.CustomerName
ORDER BY SUM(z.ВыручкаЗаказа) DESC;


-- ---------------------------------------------------------------------------------------------
-- 8. Выручка по менеджерам (нужен qry_ВыручкаЗаказов из шапки)
-- Employees присоединяем по ManagerID;qry_ВыручкаЗаказов даёт ровно одну строку на заказ,
-- поэтому COUNT и SUM не искажаются позициями.
-- Ожидаемый результат: 5 строк по убыванию:
--   Maria Oliveira  3 заказа  1 236,10  (776,50 + 189,90 + 269,70)
--   Pedro Santos    3 заказа    759,40  (369,70 + 259,80 + 129,90)
--   Ana Souza       3 заказа    730,50  (149,00 + 283,50 + 298,00)
--   Lucas Ferreira  1 заказ     239,60  (отменённый O-10006 отфильтрован в qry_ВыручкаЗаказов)
--   Rafael Lima     1 заказ      59,90
--   Julia Pereira не выведена: у неё нет ни одного заказа (INNER JOIN отсекает пустые пары;
--   чтобы увидеть её с нулями, замените первый INNER JOIN на LEFT JOIN).
--   Контроль: сумма столбца Выручка = 3 025,50.
-- ---------------------------------------------------------------------------------------------
SELECT e.EmployeeName AS Менеджер, COUNT(o.OrderID) AS Заказов, SUM(z.ВыручкаЗаказа) AS Выручка
FROM (Employees AS e INNER JOIN Orders AS o ON e.EmployeeID = o.ManagerID)
     INNER JOIN qry_ВыручкаЗаказов AS z ON o.OrderID = z.OrderID
GROUP BY e.EmployeeName
ORDER BY SUM(z.ВыручкаЗаказа) DESC;
