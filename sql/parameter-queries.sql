-- parameter-queries.sql — параметрические запросы. Курс «Microsoft Access 2007–2016
-- для аналитика», модуль 8 «Аналитические запросы».
--
-- НАЗНАЧЕНИЕ ФАЙЛА
--   Пять запросов к мини-датасету ShopData (Orders = 12, Customers = 8, Products = 8,
--   OrderDetails = 15). Параметр — значение, которое Access запрашивает у пользователя
--   в момент выполнения запроса.
--
-- КАК ИСПОЛЬЗОВАТЬ
--   Вставляйте ОДИН блок в окно SQL-режима конструктора запросов (строки «--» не копируйте:
--   комментарии в Access не работают — они только для чтения здесь).
--   Блоки 1 и 3 начинаются с объявления PARAMETERS и завершаются обычным SELECT: вставляйте
--   их ЦЕЛИКОМ одной вставкой (PARAMETERS — это шапка запроса, Access сохранит её вместе с ним).
--   При запуске Access покажет диалог «Введите значение параметра».
--
-- ВАЖНО: если параметр в квадратных скобках совпадает с именем реального поля, Access
--   молча примет его за поле и фильтр «молча» не сработает. Поэтому в тексте параметров
--   пишут подсказку: [Введите статус], а не просто [OrderStatus].
-- =====================================================================================


-- ---------------------------------------------------------------------------------------------
-- 1. Явное объявление PARAMETERS с типами DateTime
-- Объявление задаёт тип данных параметров: Access правильно поймёт ввод «01.01.2018» как дату,
-- а не текст, и покажет корректные диалоги.
-- Ожидаемый результат при вводе 01.01.2018 и 31.03.2018: 3 строки —
--   O-10007 (2018-01-17, delivered), O-10008 (2018-02-14, delivered), O-10009 (2018-03-08, delivered).
--   При вводе 01.01.2018 и 31.12.2018 — 6 строк (O-10007, O-10008, O-10009, O-10010, O-10011, O-10012).
-- ---------------------------------------------------------------------------------------------
PARAMETERS [Начальная дата] DateTime, [Конечная дата] DateTime;
SELECT o.OrderID, o.CustomerID, o.OrderStatus, o.OrderDate
FROM Orders AS o
WHERE o.OrderDate BETWEEN [Начальная дата] AND [Конечная дата]
ORDER BY o.OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 2. Быстрый параметр в квадратных скобках: [Введите статус]
-- Если в условии встречается слово в квадратных скобках, не являющееся полем или формой,
-- Access сам создаёт текстовый параметр — объявление PARAMETERS не обязательно.
-- Ожидаемый результат: при вводе delivered — 9 строк; canceled — 1 строка (O-10006);
--   shipped — 1 строка (O-10005); processing — 1 строка (O-10010).
-- ---------------------------------------------------------------------------------------------
SELECT o.OrderID, o.CustomerID, o.OrderDate
FROM Orders AS o
WHERE o.OrderStatus = [Введите статус]
ORDER BY o.OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 3. Параметр внутри шаблона Like (поиск по началу названия)
-- К введённому пользователем тексту конкатенацией & приклеивается подстановочный знак *
-- (ANSI-89). Тип Text (255) явно объявляет параметр строковым.
-- Ожидаемый результат: при вводе «Крем» — 1 строка (P-2001 Крем для лица SPF30);
--   «Подушка» — 1 строка (P-1002 Подушка ортопедическая); «Б» — 2 строки (P-2002 Витамин C 1000 мг
--   и P-3001 Беспроводная мышь); пустой ввод — все 8 товаров (шаблон превращается в "*").
-- ---------------------------------------------------------------------------------------------
PARAMETERS [Начало названия] Text ( 255 );
SELECT p.ProductID, p.ProductName
FROM Products AS p
WHERE p.ProductName Like [Начало названия] & "*"
ORDER BY p.ProductName;


-- ---------------------------------------------------------------------------------------------
-- 4. Параметр из формы: Forms!frm_Панель!НачальнаяДата
-- Вместо диалога запрос читает значение поля НачальнаяДата открытой формы frm_Панель.
-- Форма должна быть ОТКРЫТА в момент выполнения; иначе Access не найдёт поле и покажет
-- обычный диалог параметра (это самая частая ошибка начинающих).
-- Ожидаемый результат: если на frm_Панель в поле НачальнаяДата стоит 01.01.2018 — 6 строк:
--   O-10007, O-10008, O-10009, O-10010, O-10011, O-10012 (все заказы 2018 года, без canceled).
--   Эквивалентная запись с полными скобками: [Forms]![frm_Панель]![НачальнаяДата].
-- ---------------------------------------------------------------------------------------------
SELECT o.OrderID, o.OrderStatus, o.OrderDate
FROM Orders AS o
WHERE o.OrderDate >= Forms!frm_Панель!НачальнаяДата AND o.OrderStatus <> "canceled"
ORDER BY o.OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 5. Параметрический агрегат: города с выручкой выше порога
-- HAVING с параметром фильтрует группы ПОСЛЕ расчёта агрегата (WHERE фильтровал бы строки).
-- Выручка города = сумма по позициям заказов без отменённых.
-- Ожидаемый результат при вводе 400: 3 строки — belo horizonte 1 046,20; sao paulo 759,40;
--   rio de janeiro 447,00. При вводе 0 — 7 городов (recife исключён: только отменённый O-10006;
--   полные значения: porto alegre 283,50; curitiba 239,60; salvador 189,90; manaus 59,90).
--   Контрольная сумма по 7 городам: 3 025,50.
-- ---------------------------------------------------------------------------------------------
PARAMETERS [Минимальная выручка] Currency;
SELECT c.City AS Город, SUM(od.Quantity * od.UnitPrice) AS Выручка
FROM (Customers AS c INNER JOIN Orders AS o ON c.CustomerID = o.CustomerID)
     INNER JOIN OrderDetails AS od ON o.OrderID = od.OrderID
WHERE o.OrderStatus <> "canceled"
GROUP BY c.City
HAVING SUM(od.Quantity * od.UnitPrice) > [Минимальная выручка]
ORDER BY SUM(od.Quantity * od.UnitPrice) DESC;
