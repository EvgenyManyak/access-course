-- action-queries.sql — запросы-действия: SELECT INTO, UPDATE, INSERT, DELETE.
-- Курс «Microsoft Access 2007–2016 для аналитика», модуль 8 «Аналитические запросы».
--
-- ОПАСНОСТЬ. Запросы-действия МЕНЯЮТ ДАННЫЕ и НЕОБРАТИМЫ (Undo в Access нет!).
--   Правила работы:
--   1) Перед экспериментами сделайте копию файла базы (ShopData.accdb → ShopData_backup.accdb).
--   2) Выполняйте ОДИН блок, проверяйте результат, затем восстанавливайте данные из копии
--      или возвращайте значения обратным запросом.
--   3) Access перед выполнением покажет предупреждение «Будет изменено/добавлено/удалено N строк»
--      — всегда читайте N и сверяйте с ожидаемым результатом из комментария.
--   4) Из кода VBA и макросов предупреждения отключаются командой DoCmd.SetWarnings False —
--      в этом случае Access выполнит запрос МОЛЧА. Всегда возвращайте DoCmd.SetWarnings True.
--   5) Make-table (SELECT INTO) не переносит ключи, индексы и связи — только данные.
--
-- КАК ИСПОЛЬЗОВАТЬ
--   Режим SQL конструктора запросов; вставлять ОДИН оператор (строки «--» не копируйте —
--   комментарии в Access не работают, они только для чтения здесь). После вставки запроса
--   нажмите «!» и подтвердите действие.
--
-- Все блоки ниже рассчитаны на исходный мини-датасет (Orders = 12, OrderDetails = 15,
-- Products = 8, Categories = 5).
-- =====================================================================================


-- ---------------------------------------------------------------------------------------------
-- 1. SELECT INTO: резервная копия таблицы товаров (make-table)
-- Создаёт НОВУЮ таблицу Products_Backup и копирует в неё все 8 строк Products.
-- Ожидаемый результат: Access сообщит «8 строк вставлено» в Products_Backup.
--   Если таблица Products_Backup уже существует, Access сначала попросит разрешение её удалить.
--   Резерв нужен перед блоками 2 и 3, которые меняют цены и стоимость доставки.
-- ---------------------------------------------------------------------------------------------
SELECT p.*
INTO Products_Backup
FROM Products AS p;


-- ---------------------------------------------------------------------------------------------
-- 2. UPDATE с соединением: цена automotivo +5%
-- Цена хранится в OrderDetails.UnitPrice (у таблицы Products поля цены нет — раздел 2.1
-- спецификации), поэтому повышаем цену через соединение трёх таблиц; скобки в FROM обязательны.
-- Ожидаемый результат: обновлена 1 строка — OrderDetailID 9 (заказ O-10007, товар P-5001
--   Насос для шин): цена 119,00 → ROUND(119,00 x 1,05; 2) = 124,95.
--   Последствия для эталонов: выручка O-10007 станет 295,40 вместо 283,50, общая выручка
--   мини-датасета 3 037,40 вместо 3 025,50 (+11,90 = 2 штуки x 5,95).
--   Откат: UPDATE OrderDetails SET UnitPrice = 119 WHERE OrderDetailID = 9;
-- ---------------------------------------------------------------------------------------------
UPDATE (OrderDetails AS od INNER JOIN Products AS p ON od.ProductID = p.ProductID)
       INNER JOIN Categories AS cat ON p.CategoryID = cat.CategoryID
SET od.UnitPrice = ROUND(od.UnitPrice * 1.05, 2)
WHERE cat.CategoryName = "automotivo";


-- ---------------------------------------------------------------------------------------------
-- 3. UPDATE с IIF: увеличение дешёвой доставки на 5
-- IIF внутри SET срабатывает построчно: если FreightValue < 15, прибавляем 5, иначе оставляем.
-- Ожидаемый результат: Access предупредит про 15 строк — это ВСЕ строки таблицы (условия WHERE
--   нет), фактически изменятся 6 позиций со стоимостью доставки меньше 15:
--   OrderDetailID 3: 12,30 → 17,30; 5: 14,20 → 19,20; 7: 9,80 → 14,80;
--   OrderDetailID 10: 14,20 → 19,20; 12: 12,30 → 17,30; 13: 8,10 → 13,10.
--   Тот же результат даст UPDATE ... SET FreightValue = FreightValue + 5 WHERE FreightValue < 15,
--   который тронет только 6 строк. Откат: верните исходные значения из Products_Backup
--   нельзя (там нет FreightValue) — используйте копию базы.
-- ---------------------------------------------------------------------------------------------
UPDATE OrderDetails
SET FreightValue = IIF(FreightValue < 15, FreightValue + 5, FreightValue);


-- ---------------------------------------------------------------------------------------------
-- 4. INSERT INTO ... VALUES: новая категория
-- Явный список полей — правильная привычка: не нужно перечислять счётчик CategoryID,
-- Access присвоит его сам.
-- Ожидаемый результат: 1 строка добавлена; CategoryID (счётчик) получит значение 6.
--   ПОВТОРНЫЙ ЗАПУСК УПАДЁТ с ошибкой «Изменения не были успешно внесены... повторяющиеся
--   значения»: на CategoryName стоит уникальный индекс — это защита от дублей справочника.
-- ---------------------------------------------------------------------------------------------
INSERT INTO Categories (CategoryName, CategoryNameEn)
VALUES ("brinquedos", "toys");


-- ---------------------------------------------------------------------------------------------
-- 5. INSERT INTO ... SELECT: загрузка из staging-таблицы без дублей
-- StagingCustomers — «черновая» таблица, в которую сырой CSV попадает при импорте (модуль 4).
-- Условие Not In пропускает покупателей, которые уже есть в основной таблице.
-- Ожидаемый результат: на чистом мини-датасете staging пуста — «0 строк добавлено».
--   Если в StagingCustomers загрузить тестовые строки C-0009 (Igor Melo, 59120, natal, RN, VIP)
--   и C-0010 (Tatiana Rocha, 69050, manaus, AM, Retail) — будут добавлены 2 строки;
--   повторный запуск добавит 0: оба CustomerID уже есть в Customers.
--   ZipCodePrefix переносится как текст — ведущие нули сохраняются.
-- ---------------------------------------------------------------------------------------------
INSERT INTO Customers (CustomerID, CustomerName, ZipCodePrefix, City, State, Segment)
SELECT s.CustomerID, s.CustomerName, s.ZipCodePrefix, s.City, s.State, s.Segment
FROM StagingCustomers AS s
WHERE s.CustomerID Not In (SELECT CustomerID FROM Customers);


-- =============================================================================================
-- 6. ВНИМАНИЕ!!! DELETE с каскадным удалением: отмена заказов
-- =============================================================================================
-- Перед выполнением ОБЯЗАТЕЛЬНО:
--   1) сделайте копию файла базы (или запрос из блока 1 — но для Orders, не Products);
--   2) помните про связи: между Orders и OrderDetails включено «обеспечение целостности
--      с каскадным удалением связанных полей», поэтому вместе с заказом БЕЗ ДОПОЛНИТЕЛЬНОГО
--      ВОПРОСА удалятся все его позиции из OrderDetails;
--   3) при желании сначала сохраните удаляемое:
--      SELECT * INTO Orders_Backup FROM Orders WHERE OrderStatus = "canceled";
-- Из кода VBA (DoCmd.SetWarnings False) подтверждение НЕ показывается — каскад сработает молча.
-- =============================================================================================
DELETE FROM Orders
WHERE OrderStatus = "canceled";
-- Ожидаемый результат: Access предупредит «Вы собираетесь удалить 1 строку(и) из Orders».
--   Будут удалены: заказ O-10006 (canceled, Elena Costa) и каскадом его единственная позиция
--   OrderDetailID 8 (P-2001, 89,90) из OrderDetails. В Orders останется 11 заказов,
--   в OrderDetails — 14 позиций. Эталонные суммы файлов курса (3 025,50 и прочие) сойдутся
--   только после восстановления данных из копии.


-- =============================================================================================
-- 7. DELETE дубликатов через DISTINCTROW
-- =============================================================================================
-- Сценарий: таблица Orders_Dup (ID — счётчик; OrderID, CustomerID, OrderStatus, OrderDate —
-- копии полей Orders) содержит 14 строк: 12 заказов мини-датасета, причём O-10001 и O-10002
-- вставлены по два раза с разными ID.
--
-- Задача: оставить по одной строке на каждый OrderID (с минимальным ID) и удалить остальные 2.
--
-- Подводный камень Jet: DELETE с подзапросом к той же таблице обычно падает с ошибкой
-- «Не удалось удалить из указанных таблиц». Слово DISTINCTROW снимает неоднозначность
-- и разрешает удаление — это классический приём Access.
--
-- Ожидаемый результат: удалено 2 строки (дубликаты с большим ID); в Orders_Dup останется
-- 12 строк — по одной на каждый заказ мини-датасета.
--
-- Перед боем протестируйте на копии: SELECT * INTO Orders_Dup_Copy FROM Orders_Dup;
-- =============================================================================================
DELETE DISTINCTROW d.*
FROM Orders_Dup AS d
WHERE d.ID Not In (SELECT MIN(ID) FROM Orders_Dup GROUP BY OrderID);


-- ---------------------------------------------------------------------------------------------
-- 8. Make-table Orders_Archive: архив заказов прошлых лет
-- Переносит в новую таблицу все заказы, сделанные ДО 2018 года.
-- Ожидаемый результат: «6 строк вставлено»: O-10001, O-10002, O-10003, O-10004, O-10005, O-10006
--   (все заказы 2017 года). В Orders_Archive не будет ключей, индексов и связей — только данные.
--   Повторный запуск сначала попросит разрешение удалить существующую Orders_Archive.
--   Реальная цепочка архивации: (1) этот запрос; (2) сверка «6 строк» с ожиданием;
--   (3) DELETE этих заказов из Orders (каскад унесёт их позиции из OrderDetails);
--   (4) Сжать и восстановить базу.
-- ---------------------------------------------------------------------------------------------
SELECT o.*
INTO Orders_Archive
FROM Orders AS o
WHERE o.OrderDate < #2018-01-01#;
