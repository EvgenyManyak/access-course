-- joins.sql — соединения таблиц (INNER/LEFT/RIGHT, SELF-JOIN, UNION, декартово произведение)
-- Курс «Microsoft Access 2007–2016 для аналитика», модуль 7 «Access SQL и соединения таблиц».
--
-- НАЗНАЧЕНИЕ ФАЙЛА
--   Девять запросов к мини-датасету ShopData: Orders = 12 строк, Customers = 8,
--   Employees = 6, Products = 8, OrderDetails = 15, Categories = 5.
--
-- КАК ИСПОЛЬЗОВАТЬ
--   1) Создайте запрос: Создание → Конструктор запросов → закройте окно добавления таблиц.
--   2) Перейдите в режим SQL и вставьте ОДИН оператор (без строк «--»).
--   3) Выполните кнопкой «!» (Выполнить).
--   ВАЖНО: комментарии в Access не работают — они только для чтения здесь.
--   Операторы независимы; порядок выполнения — любой, данные запросы не меняют.
--
-- ДИАЛЕКТ: Access SQL. При соединении ТРЁХ и более таблиц Access требует круглые скобки
--   вокруг пар соединений — они расставлены в запросах ниже и убирать их нельзя.
--   Псевдонимы таблиц (AS o, AS c) сокращают запись и обязательны для SELF-JOIN.
-- =====================================================================================


-- ---------------------------------------------------------------------------------------------
-- 1. INNER JOIN: заказы + покупатели (2 таблицы)
-- INNER JOIN оставляет только пары строк с совпадением по условию ON.
-- Ожидаемый результат: 12 строк — по одной на каждый заказ (CustomerID заполнен у всех 12).
--   Первые строки по дате: O-10001 | Ana Ribeiro | sao paulo | 2017-03-15,
--   O-10002 | Bruno Carvalho | rio de janeiro | 2017-04-02, O-10003 | Carla Mendes | 2017-06-21.
-- ---------------------------------------------------------------------------------------------
SELECT o.OrderID, o.OrderDate, o.OrderStatus, c.CustomerName, c.City
FROM Orders AS o INNER JOIN Customers AS c ON o.CustomerID = c.CustomerID
ORDER BY o.OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 2. INNER JOIN трёх таблиц: Orders + Customers + Employees
-- Каждая следующая таблица присоединяется отдельным INNER JOIN; пары соединений взяты в скобки.
-- Ожидаемый результат: 12 строк. Пример: O-10001 | Ana Ribeiro | Pedro Santos | 2017-03-15
--   (у заказа O-10001 ManagerID = 2, а EmployeeID 2 — это Pedro Santos).
-- ---------------------------------------------------------------------------------------------
SELECT o.OrderID, c.CustomerName, e.EmployeeName AS Менеджер, o.OrderDate
FROM (Orders AS o INNER JOIN Customers AS c ON o.CustomerID = c.CustomerID)
     INNER JOIN Employees AS e ON o.ManagerID = e.EmployeeID
ORDER BY o.OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 3. Четыре таблицы и вычисляемая сумма позиции
-- Цепочка: Orders → Customers (кто купил), Orders → OrderDetails (что куплено),
-- OrderDetails → Products (название товара). Стоимость строки = Quantity * UnitPrice.
-- Ожидаемый результат: 15 строк — по одной на каждую позицию. Примеры:
--   O-10001 | Ana Ribeiro | Набор постельного белья 2-сп | 1 | 189,90 | 189,90
--   O-10001 | Ana Ribeiro | Крем для лица SPF30 | 2 | 89,90 | 179,80
--   O-10003 | Carla Mendes | Торшер деревянный | 1 | 640,00 | 640,00
-- ---------------------------------------------------------------------------------------------
SELECT o.OrderID, c.CustomerName, p.ProductName, od.Quantity, od.UnitPrice,
       od.Quantity * od.UnitPrice AS [Сумма позиции]
FROM ((Orders AS o INNER JOIN Customers AS c ON o.CustomerID = c.CustomerID)
     INNER JOIN OrderDetails AS od ON o.OrderID = od.OrderID)
     INNER JOIN Products AS p ON od.ProductID = p.ProductID
ORDER BY o.OrderID, p.ProductID;


-- ---------------------------------------------------------------------------------------------
-- 4. Анти-соединение через LEFT JOIN ... Is Null: товары, которые ни разу не заказывали
-- LEFT JOIN сохраняет ВСЕ товары; условие Is Null отбирает те, к которым не нашлось позиций.
-- В поле-счётчике проверяем OrderDetailID — это счётчик, он не бывает пустым у нашедшейся пары.
-- Ожидаемый результат: 0 строк — в мини-датасете каждый из 8 товаров заказан хотя бы раз
--   (реже всего заказывали P-4001 и P-5001 — по одной позиции). Добавьте в Products строку
--   P-6001 «Тестовый товар» без позиций — и запрос вернёт её.
-- ---------------------------------------------------------------------------------------------
SELECT p.ProductID, p.ProductName
FROM Products AS p LEFT JOIN OrderDetails AS od ON p.ProductID = od.ProductID
WHERE od.OrderDetailID Is Null
ORDER BY p.ProductID;


-- ---------------------------------------------------------------------------------------------
-- 5. RIGHT JOIN: все сотрудники, включая тех, у кого нет заказов
-- RIGHT JOIN сохраняет все строки ПРАВОЙ таблицы (Employees); чужим полям будет пусто.
-- Ожидаемый результат: 13 строк = 12 заказов + 1 строка Julia Pereira с пустым OrderID
--   (у Julia EmployeeID = 5, менеджером ни одного заказа она не была).
--   Распределение заказов по менеджерам: Ana Souza — 3, Pedro Santos — 3, Maria Oliveira — 3,
--   Lucas Ferreira — 2 (включая отменённый O-10006), Rafael Lima — 1, Julia Pereira — 0.
--   Запрос o RIGHT JOIN e эквивалентен e LEFT JOIN o — в конструкторе Access показывает его как LEFT.
-- ---------------------------------------------------------------------------------------------
SELECT e.EmployeeName AS Менеджер, o.OrderID, o.OrderDate
FROM Orders AS o RIGHT JOIN Employees AS e ON o.ManagerID = e.EmployeeID
ORDER BY e.EmployeeName, o.OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 6. SELF-JOIN: сотрудник и «его» менеджер по городу
-- Таблица Employees соединяется сама с собой под двумя псевдонимами (w — работник, m — менеджер).
-- Поля ManagerID в Employees нет (раздел 2.1 спецификации), поэтому пары собираем по городу:
-- работник из того же города, где работает сотрудник с ролью «Менеджер».
-- В классической структуре с полем ManagerID условие было бы ON w.ManagerID = m.EmployeeID.
-- Ожидаемый результат: 1 строка: Pedro Santos | Ana Souza (оба в sao paulo).
--   Остальные пары не складываются: Maria Oliveira сама менеджер в rio de janeiro (исключена
--   условием w.EmployeeID <> m.EmployeeID), а в curitiba, belo horizonte и salvador менеджеров нет.
-- ---------------------------------------------------------------------------------------------
SELECT w.EmployeeName AS Сотрудник, m.EmployeeName AS [Менеджер города]
FROM Employees AS w INNER JOIN Employees AS m ON w.City = m.City
WHERE m.Role = "Менеджер" AND w.EmployeeID <> m.EmployeeID
ORDER BY w.EmployeeName;


-- ---------------------------------------------------------------------------------------------
-- 7. Анти-соединение: покупатели без единого заказа
-- Шаблон тот же, что в блоке 4, но со стороны Customers.
-- Ожидаемый результат: 0 строк — все 8 покупателей сделали хотя бы один заказ.
--   Пограничный случай: Elena Costa (C-0005) оформила только отменённый O-10006, но заказ
--   формально есть, поэтому в анти-соединение она не попадает. Если удалите из Orders строку
--   O-10006, запрос вернёт «Elena Costa».
-- ---------------------------------------------------------------------------------------------
SELECT c.CustomerID, c.CustomerName
FROM Customers AS c LEFT JOIN Orders AS o ON c.CustomerID = o.CustomerID
WHERE o.OrderID Is Null
ORDER BY c.CustomerID;


-- ---------------------------------------------------------------------------------------------
-- 8. UNION: города покупателей и сотрудников одним списком
-- UNION склеивает результаты двух SELECT и убирает ПОЛНЫЕ дубли строк; имена столбцов
-- берутся из первого SELECT. Столбец Источник показывает, откуда строка.
-- Ожидаемый результат: 13 строк = 8 городов покупателей + 5 городов сотрудников
--   (sao paulo, rio de janeiro, curitiba, belo horizonte, salvador; sao paulo у сотрудников
--   встречается дважды и схлопывается до одной строки).
--   Без столбца Источник UNION вернул бы 8 строк (города совпадают), а UNION ALL — 14 строк
--   (8 + 6, без удаления дублей, включая второй sao paulo у сотрудников).
-- ---------------------------------------------------------------------------------------------
SELECT City AS Город, "Покупатель" AS Источник FROM Customers
UNION
SELECT City, "Сотрудник" FROM Employees
ORDER BY Город;


-- =============================================================================================
-- 9. ВНИМАНИЕ!!! ДЕКАРТОВО ПРОИЗВЕДЕНИЕ — НЕ ВЫПОЛНЯЙТЕ НА РАБОЧИХ ДАННЫХ!
-- =============================================================================================
-- Здесь НЕТ условия соединения (запятая вместо JOIN ... ON): каждая строка Customers
-- сочетается с КАЖДОЙ строкой Employees.
--
--   8 покупателей x 6 сотрудников = 48 строк. На мини-датасете это ещё терпимо.
--
--   Но масштаб растёт умножением! На реальном объёме Olist это выглядит так:
--   99 441 заказ x 32 951 товар = около 3,3 МИЛЛИАРДА строк. Access начнёт раздувать
--   временный файл, зависнет или выдаст «Недостаточно системных ресурсов».
--
--   Типичная причина декартова произведения — забытый ON после добавления таблицы
--   в конструкторе или запятая в FROM. Всегда проверяйте число строк результата:
--   если строк «слишком много» — вы, скорее всего, получили именно его.
--
-- Запрос приведён только для демонстрации. Ожидаемый результат: ровно 48 строк
-- (каждое имя покупателя повторено 6 раз — по числу сотрудников).
-- =============================================================================================
SELECT c.CustomerName, e.EmployeeName
FROM Customers AS c, Employees AS e
ORDER BY c.CustomerName, e.EmployeeName;
