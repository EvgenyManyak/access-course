-- =====================================================================================
-- select-examples.sql — примеры запросов SELECT для курса
-- «Microsoft Access 2007–2016 для аналитика», модули 6–7 (фильтрация, SQL-режим).
--
-- НАЗНАЧЕНИЕ ФАЙЛА
--   Девять готовых запросов на выборку к мини-датасету ShopData (раздел 2.3 module-spec):
--   Categories = 5 строк, Products = 8, Customers = 8, Employees = 6,
--   Orders = 12, OrderDetails = 15.
--
-- КАК ИСПОЛЬЗОВАТЬ
--   1) Откройте учебную базу ShopData.accdb.
--   2) Создание → Конструктор запросов → закройте окно «Добавление таблицы».
--   3) Переключитесь в режим SQL (вкладка с надписью SQL в левом верхнем углу листа запроса).
--   4) Скопируйте ОДИН оператор (без строк «--») в окно SQL и выполните кнопкой с восклицательным знаком.
--   ВАЖНО: комментарии в Access не работают — строки с «--» существуют только для чтения здесь.
--   Каждый оператор заканчивается точкой с запятой; вставляйте блоки по одному.
--
-- ДИАЛЕКТ: Access SQL (JET/ACE). Даты #2018-03-01#, подстановочный знак * в Like (ANSI-89),
--   IIF вместо CASE, FORMAT вместо CONVERT, конкатенация &, квадратные скобки для имён с пробелами.
--   Если база работает в режиме ANSI-92 и Access ругается на кавычки — замените "текст" на 'текст'.
--
-- Все значения «Ожидаемый результат» пересчитаны по мини-датасету вручную.
-- =====================================================================================


-- ---------------------------------------------------------------------------------------------
-- 1. TOP 5 товаров по выручке
-- TOP N возвращает первые N строк УЖЕ отсортированного набора, поэтому ORDER BY обязателен.
-- Выручка позиции = Quantity * UnitPrice (FreightValue здесь не учитываем).
-- Ожидаемый результат: 5 строк по убыванию:
--   P-4001 Торшер деревянный 640,00; P-2001 Крем для лица SPF30 539,40; P-3001 Беспроводная мышь 447,00;
--   P-1002 Подушка ортопедическая 389,70; P-1001 Набор постельного белья 2-сп 379,80.
--   Следом идёт P-3002 USB-хаб 4 порта (299,50) — в топ не попадает.
--   Заметьте: P-2001 включает позицию отменённого заказа O-10006 (89,90) — фильтра по статусу здесь нет.
-- ---------------------------------------------------------------------------------------------
SELECT TOP 5 p.ProductID, p.ProductName, SUM(od.Quantity * od.UnitPrice) AS Выручка
FROM Products AS p INNER JOIN OrderDetails AS od ON p.ProductID = od.ProductID
GROUP BY p.ProductID, p.ProductName
ORDER BY SUM(od.Quantity * od.UnitPrice) DESC;


-- ---------------------------------------------------------------------------------------------
-- 2. Выборка по состоянию (State = "SP")
-- Простейший фильтр по текстовому полю: значение в двойных кавычках, точное совпадение.
-- Ожидаемый результат: 1 строка — C-0001, Ana Ribeiro, sao paulo, Retail.
--   В Customers штату SP соответствует только один покупатель; для сравнения: среди сотрудников
--   из SP двое (Ana Souza и Pedro Santos) — см. таблицу Employees.
-- ---------------------------------------------------------------------------------------------
SELECT CustomerID, CustomerName, City, Segment
FROM Customers
WHERE State = "SP"
ORDER BY CustomerName;


-- ---------------------------------------------------------------------------------------------
-- 3. BETWEEN по датам: заказы марта 2018
-- BETWEEN включает ОБЕ границы. Даты в Access пишутся в решётках: #2018-03-01#.
-- Ожидаемый результат: 1 строка — O-10009, C-0002, delivered, 2018-03-08.
--   В марте 2018 в мини-датасете всего один заказ. Расширить период можно так:
--   BETWEEN #2018-01-01# AND #2018-03-31# даст 3 строки (O-10007, O-10008, O-10009).
-- ---------------------------------------------------------------------------------------------
SELECT OrderID, CustomerID, OrderStatus, OrderDate
FROM Orders
WHERE OrderDate BETWEEN #2018-03-01# AND #2018-03-31#
ORDER BY OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 4. IN (…): несколько значений одного поля
-- IN заменяет цепочку условий OR и читается легче.
-- Ожидаемый результат: 3 строки: C-0001 sao paulo (SP), C-0002 rio de janeiro (RJ), C-0003 belo horizonte (MG).
-- ---------------------------------------------------------------------------------------------
SELECT CustomerID, CustomerName, City, State
FROM Customers
WHERE State IN ("SP", "RJ", "MG")
ORDER BY State, CustomerName;


-- ---------------------------------------------------------------------------------------------
-- 5. Like с подстановочным знаком * (ANSI-89 — режим Access по умолчанию)
-- Шаблон "P-3*" означает: начинается с P-3, дальше любые символы.
-- Ожидаемый результат: 2 строки: P-3001 Беспроводная мышь, P-3002 USB-хаб 4 порта.
--   Прочие примеры шаблонов: "P-1*" даст P-1001 и P-1002; "*мышь*" найдёт подстроку в середине названия.
--   Процент % как в SQL Server здесь НЕ работает (он для ANSI-92/DAO/ADO — см. модуль 7).
-- ---------------------------------------------------------------------------------------------
SELECT ProductID, ProductName
FROM Products
WHERE ProductID Like "P-3*"
ORDER BY ProductID;


-- ---------------------------------------------------------------------------------------------
-- 6. Is Null: недоставленные заказы
-- Пустое значение проверяется только конструкцией Is Null; условие "= Null" всегда даёт Неизвестно
-- и строк не вернёт. DeliveredDate пуст у трёх заказов мини-датасета.
-- Ожидаемый результат: 3 строки: O-10005 (shipped, 2017-10-30), O-10006 (canceled, 2017-11-05),
--   O-10010 (processing, 2018-04-22).
-- ---------------------------------------------------------------------------------------------
SELECT OrderID, OrderStatus, OrderDate
FROM Orders
WHERE DeliveredDate Is Null
ORDER BY OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 7. Вычисляемые поля: IIF, FORMAT и Nz
-- IIF(условие; да; нет) — доступный аналог CASE; FORMAT превращает дату в текст нужного вида
-- вместо CONVERT; Nz подставляет замену для пустого значения.
-- Ожидаемый результат: 12 строк. СтатусДоставки = "Доставлен" у 9 заказов, "Не доставлен" у 3
--   (O-10005, O-10006, O-10010). Для O-10005 столбец [Дата для отчёта] покажет дату заказа
--   2017-10-30, потому что Nz подставит OrderDate вместо пустого DeliveredDate.
--   МесяцЗаказа: 2017-03, 2017-04, 2017-06, 2017-08, 2017-10, 2017-11, 2018-01, 2018-02,
--   2018-03, 2018-04, 2018-05, 2018-06 — каждый месяц по одному заказу.
--   Псевдоним [Дата для отчёта] содержит пробел, поэтому заключён в квадратные скобки.
-- ---------------------------------------------------------------------------------------------
SELECT OrderID,
       FORMAT(OrderDate, "yyyy-mm") AS МесяцЗаказа,
       FORMAT(Nz(DeliveredDate, OrderDate), "yyyy-mm-dd") AS [Дата для отчёта],
       IIF(DeliveredDate Is Null, "Не доставлен", "Доставлен") AS СтатусДоставки
FROM Orders
ORDER BY OrderDate;


-- ---------------------------------------------------------------------------------------------
-- 8. DISTINCT: список городов без повторов
-- DISTINCT убирает дубликаты уже ВЫВЕДЕННЫХ строк результата.
-- Ожидаемый результат: 8 строк (у всех покупателей города разные): belo horizonte, curitiba,
--   manaus, porto alegre, recife, rio de janeiro, salvador, sao paulo.
-- ---------------------------------------------------------------------------------------------
SELECT DISTINCT City
FROM Customers
ORDER BY City;


-- ---------------------------------------------------------------------------------------------
-- 9. DISTINCTROW: уникальные строки ИСХОДНОЙ таблицы после соединения
-- Соединение Customers + Orders само по себе вернёт 12 строк (по одной на заказ): покупатели
-- C-0001 — трижды, C-0002 и C-0003 — по два раза. DISTINCTROW оставит по одной строке
-- на каждую строку таблицы Customers, участвующую в соединении.
-- Ожидаемый результат: 8 строк (C-0001, C-0002, C-0003, C-0004, C-0005, C-0006, C-0007, C-0008
--   — каждый покупатель один раз). Тот же запрос без DISTINCTROW вернул бы 12 строк.
-- Отличие от DISTINCT: DISTINCTROW работает по строкам базовых таблиц, а DISTINCT — по итоговому
-- набору столбцов. Для одной таблицы без соединения дубликаты полей убирает DISTINCT (блок 8),
-- DISTINCTROW в этом случае дубликаты НЕ уберёт.
-- ---------------------------------------------------------------------------------------------
SELECT DISTINCTROW c.CustomerID, c.CustomerName
FROM Customers AS c INNER JOIN Orders AS o ON c.CustomerID = o.CustomerID
ORDER BY c.CustomerID;
